function hexToRgb(hex) {
  return [0, 2, 4].map((offset) => Number.parseInt(hex.slice(offset, offset + 2), 16));
}

function buildPam(name, runs) {
  const pixels = Array.from({ length: HEIGHT }, () => Array(WIDTH).fill(null));
  for (const [y, start, end, color] of runs) {
    if (y < 0 || y >= HEIGHT || start < 0 || end >= WIDTH || start > end) throw new Error(`Invalid ${name} run`);
    for (let x = start; x <= end; x += 1) pixels[y][x] = color;
  }

  const bytes = [];
  for (const row of pixels) for (const key of row) {
    if (key === null) bytes.push(0, 0, 0, 0);
    else bytes.push(...hexToRgb(palettes[name][key]), 255);
  }

  const header = `P7\nWIDTH ${WIDTH}\nHEIGHT ${HEIGHT}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n`;
  writeFileSync(new URL(`${name}.pam`, OUTPUT), Buffer.concat([Buffer.from(header), Buffer.from(bytes)]));
}

