for char, source in {"—":"-", "–":"-", "−":"-", "’":"'", "‘":"'", "“":'"', "”":'"', "\u00a0":" "}.items():
    ROWS[char] = ROWS[source]
order = [".notdef"] + [f"u{ord(c):04X}" for c in ROWS]
fb = FontBuilder(1024, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({ord(c): f"u{ord(c):04X}" for c in ROWS})
glyphs = {}
for name, pattern in [(".notdef", ROWS["?"])] + [(f"u{ord(c):04X}", rows) for c, rows in ROWS.items()]:
    pen = TTGlyphPen(None)
    for y, row in enumerate(pattern.split("/")):
        for x, bit in enumerate(row):
            if bit != "1": continue
            left, bottom = x * 128, (6 - y) * 128
            pen.moveTo((left, bottom)); pen.lineTo((left, bottom + 128))
            pen.lineTo((left + 128, bottom + 128)); pen.lineTo((left + 128, bottom)); pen.closePath()
    glyphs[name] = pen.glyph()
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({name: (768, 0) for name in order})
fb.setupHorizontalHeader(ascent=896, descent=-128)
fb.setupNameTable({"familyName":"Reef Pixel", "styleName":"Regular", "uniqueFontIdentifier":"KingOfTheReef-ReefPixel-1", "fullName":"Reef Pixel", "psName":"ReefPixel-Regular", "version":"Version 1.0"})
fb.setupOS2(sTypoAscender=896, sTypoDescender=-128, sTypoLineGap=0, usWinAscent=896, usWinDescent=128)
fb.setupPost(); fb.setupMaxp()
fb.save(OUT / "reef-pixel.ttf")

