import fs from 'node:fs';
import assert from 'node:assert/strict';
import {summarizeVoyages} from './roster-voyage-report.mjs';

const policies=['baseline','recruit','trim','both'];
const lines=['# Deliberate school study evidence','','Generated by `node scripts/balance/school-evidence.mjs`. See [protocol and interpretation](DELIBERATE_SCHOOL_STUDY.md). Each policy uses 96 runs per batch: 12 shared map seeds × two player policies × two route policies × two catch assumptions.','','| Seeds | Policy | W / L / cap | Ocean / Bermuda reached | Matches | Shortages | Fish / charm buys | Releases / visits | Final healthy |','| --- | --- | --- | --- | ---: | ---: | --- | --- | ---: |'];
const paired=[];
for(const start of [0,12]){
 const runs=JSON.parse(fs.readFileSync(`.cache/balance/school-study-${start}.json`,'utf8'));
 assert.equal(runs.length,384);
 const key=r=>JSON.stringify([r.seed,r.playerDifficulty,r.route,r.catchRate]);
 const baseline=new Map(runs.filter(r=>r.schoolPolicy==='baseline').map(r=>[key(r),r]));
 const keys=new Set(runs.map(r=>JSON.stringify([r.schoolPolicy,key(r)])));
 for(let i=start;i<start+12;i++)for(const player of ['tactical','expert'])for(const route of ['recovery','combat'])for(const catchRate of [.85,.6])for(const p of policies){
  assert.ok(keys.has(JSON.stringify([p,JSON.stringify([`ROSTER-VOYAGE-v6-${i}`,player,route,catchRate])])));
 }
 assert.ok(runs.every(r=>r.balanceVersion===6&&r.format==='two-tide'));
 for(const p of policies){
  const cohort=runs.filter(r=>r.schoolPolicy===p),s=summarizeVoyages(cohort),visits=cohort.flatMap(r=>r.visits);
  lines.push(`| ${start}–${start+11} | ${p} | ${s.won} / ${s.lost} / ${s.capped} | ${s.reached[1]} / ${s.reached[2]} | ${s.matches} | ${s.lowSchoolBattles} | ${s.fishPurchases} / ${s.charmPurchases} | ${visits.filter(v=>v.trimmed).length} / ${visits.filter(v=>v.type==='release').length} | ${s.endingHealthy} |`);
  if(p!=='baseline'){
   const farther=cohort.filter(r=>r.region>baseline.get(key(r)).region).length,earlier=cohort.filter(r=>r.region<baseline.get(key(r)).region).length;
   const gainedWins=cohort.filter(r=>r.status==='won'&&baseline.get(key(r)).status!=='won').length,lostWins=cohort.filter(r=>r.status!=='won'&&baseline.get(key(r)).status==='won').length;
   paired.push(`| ${start}–${start+11} | ${p} | ${farther} / ${earlier} / ${96-farther-earlier} | ${gainedWins} / ${lostWins} |`);
  }
 }
}
lines.push('','## Paired outcomes','','Farther/earlier compares the furthest region reached for the same seed, player, route and catch assumption. It does not rank draws, defeat and capped attempts within a region. Gained/lost wins count individual paired runs, not a difference between unrelated cohorts.','','| Seeds | Policy versus baseline | Farther / earlier / same region | Gained / lost wins |','| --- | --- | --- | --- |',...paired,'');
fs.writeFileSync('docs/DELIBERATE_SCHOOL_EVIDENCE.md',lines.join('\n'));
console.log('Wrote evidence for 768 runs across 24 map seeds.');
